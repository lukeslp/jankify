#!/usr/bin/env python3
"""
File Purpose: Generate the in-app open-source licenses page for Android.
Primary Functions: Join the packaged notice files into one static, offline HTML page.
Inputs/Outputs: Reads LICENSE, licenses/*.txt and the Create bundle's license;
writes android/app/src/main/assets/licenses.html.
"""
import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LICENSES = ROOT / "licenses"
OUTPUT = ROOT / "android/app/src/main/assets/licenses.html"
# Notice files in licenses/ that cover build tools, not code inside the app.
NOT_IN_APP = {"Gradle-LICENSE.txt"}

# (heading, where it is used, notice files in order, relative to the repository root)
SECTIONS = [
    (
        "Jankify",
        "The editor, the Create workspace and this Android app. MIT License.",
        ["LICENSE"],
    ),
    (
        "Rough.js 4.6.6",
        "Draws the Rough look in Edit. MIT License.",
        ["licenses/Rough-MIT.txt"],
    ),
    (
        "Pixel Space, Pixel Planets and Sprite Generator by Deep-Fold",
        "The Create generators build on these projects. MIT License.",
        [
            "Jankify/Resources/Web/create/LICENSE.txt",
            "licenses/Deep-Fold-PixelPlanets-MIT.txt",
            "licenses/Deep-Fold-SpriteGenerator-MIT.txt",
        ],
    ),
    (
        "AndroidX, Kotlin and kotlinx.coroutines",
        "Android support libraries (androidx.core and the libraries it depends on), the "
        "Kotlin standard library and kotlinx.coroutines. Apache License 2.0. "
        "Copyright The Android Open Source Project and JetBrains s.r.o. and contributors.",
        ["licenses/Apache-2.0.txt"],
    ),
]

STYLE = """
:root { color-scheme: light dark; --bg: #fafaf7; --fg: #1a1a1a; --muted: #6b6862; --border: #e4e1d8; }
@media (prefers-color-scheme: dark) {
  :root { --bg: #16140f; --fg: #f0ebe0; --muted: #9b958a; --border: #2e2a22; }
}
* { box-sizing: border-box; }
body { margin: 0; padding: 16px; background: var(--bg); color: var(--fg);
  font: 14px/1.5 system-ui, sans-serif; overflow-wrap: anywhere; }
h1 { font-size: 1.25rem; margin: 0 0 8px; }
h2 { font-size: 1.05rem; margin: 28px 0 4px; padding-top: 16px; border-top: 1px solid var(--border); }
p { margin: 0 0 10px; }
.muted { color: var(--muted); }
pre { margin: 0 0 12px; white-space: pre-wrap; font: 12px/1.45 ui-monospace, monospace; }
.license { margin: 0 0 12px; font-size: 13px; }
.heading { font-weight: 600; }
"""


def reflow(text: str) -> list[tuple[str, list[str]]]:
    """Split a hard-wrapped license into blocks a narrow screen can wrap itself.

    Returns (kind, lines): "p" is a paragraph whose lines are rejoined, "h" is a short
    centered heading kept line by line, "pre" is a code comment kept exactly as written.
    """
    blocks = []
    for raw in re.split(r"\n[ \t]*\n", text.strip("\n")):
        lines = [line.rstrip() for line in raw.split("\n") if line.strip()]
        if not lines:
            continue
        stripped = [line.strip() for line in lines]
        if stripped[0].startswith("/*") or any(line.startswith("*") for line in stripped):
            blocks.append(("pre", lines))
        elif len(lines) <= 4 and all(len(l) - len(l.lstrip()) >= 8 and len(l.strip()) < 60 for l in lines):
            blocks.append(("h", stripped))
        else:
            blocks.append(("p", [" ".join(stripped)]))
    return blocks


def check_words(name: str, text: str, blocks: list[tuple[str, list[str]]]) -> None:
    """Fail the build if reflowing dropped, added or reordered a single word."""
    before = text.split()
    after = " ".join(line for _, lines in blocks for line in lines).split()
    if before != after:
        raise SystemExit(f"Reflowing {name} changed its words; refusing to write the page.")


def render(blocks: list[tuple[str, list[str]]]) -> list[str]:
    out = []
    for kind, lines in blocks:
        if kind == "pre":
            out.append("<pre>" + html.escape("\n".join(lines)) + "</pre>")
        elif kind == "h":
            out.append('<p class="license heading">' + "<br>".join(html.escape(l) for l in lines) + "</p>")
        else:
            out.append('<p class="license">' + html.escape(lines[0]) + "</p>")
    return out


def main() -> int:
    used = set()
    parts = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        "<title>Open-source licenses</title>",
        "<!-- Generated by scripts/build-android-licenses.py. Do not edit by hand. -->",
        f"<style>{STYLE}</style>",
        "</head>",
        "<body>",
        "<h1>Open-source licenses</h1>",
        '<p class="muted">Jankify includes the open-source code listed here. '
        "Each license is printed in full, with its line breaks removed so it fits this screen. "
        "The same files, unchanged, are in the app's licenses folder and in its "
        "source repository.</p>",
    ]
    for heading, blurb, files in SECTIONS:
        parts.append(f"<h2>{html.escape(heading)}</h2>")
        parts.append(f"<p>{html.escape(blurb)}</p>")
        for name in files:
            path = ROOT / name
            if not path.is_file():
                print(f"Missing notice file: {path}", file=sys.stderr)
                return 1
            used.add(name)
            text = path.read_text(encoding="utf-8")
            blocks = reflow(text)
            check_words(name, text, blocks)
            parts.extend(render(blocks))
    shown = {pathlib.PurePosixPath(name).name for name in used}
    unlisted = sorted(
        p.name for p in LICENSES.glob("*.txt") if p.name not in shown and p.name not in NOT_IN_APP
    )
    if unlisted:
        print(f"Notice files not shown on the licenses page: {unlisted}", file=sys.stderr)
        return 1
    parts += ["</body>", "</html>", ""]
    OUTPUT.write_text("\n".join(parts), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
